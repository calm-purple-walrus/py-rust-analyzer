#[pymodule]
fn rust_analyzer_wrapper(module: &Bound<'_, PyModule>) -> PyResult<()> {
    module.add_class::<database::Database>()?;
    module.add_function(wrap_pyfunction!(load_workspace::load_workspace, module)?)?;
    types::register(module)
}
